def bm25Search(query, bm25Model, docIds):
    queryTokens = preprocessText(query)
    docScores = bm25Model.get_scores(queryTokens)
    topIndices = np.argsort(docScores)[::-1][:10]
    results = []
    for i in topIndices:
        if docScores[i] > 0 :
            results.append((docIds[i] , docScores[i]) )
    return results

