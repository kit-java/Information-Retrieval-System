def preprocessText(text):

    #Μετέτρεψα όλα τα γράμματα σε lowercase για μειωθέι το μέγεθος του
    #λεξιλογιου (μην περιλαμβάνει και Apple και apple)
    text = text.lower()


     # Αφαιρεσα τους ειδικούς χαρακτήρες και κράτησα μόνο τα γράμματα χρησιμοποιώντας regex.
    text = re.sub(r'[^a-z\s]', '', text )

      #Έκανα tokenization
    tokens = nltk.word_tokenize( text )

    #Εφάρμοσα stemming και αφαίρεσα τα stopwords
    cleanedTokens  = [stemmer.stem(t) for t in tokens if t not in stopWords ]

    return cleanedTokens

