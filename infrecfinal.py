def vsmSearch(query, vectorizerModel, matrix, docIds ) :
    queryVec =  vectorizerModel.transform([" ".join(preprocessText(query))])
    cosineSim =  cosine_similarity(queryVec, matrix).flatten()
    relatedDocsIndices =  cosineSim.argsort()[::-1][:10]

    results  = []
    for i in relatedDocsIndices:
        if cosineSim[i]  > 0 :
            results.append( (docIds[i] , cosineSim[i]))
    return  results

