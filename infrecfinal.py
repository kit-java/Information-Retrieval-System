#Boolean searchh
def booleanSearch(query, index , allDocs):

  parts  = query.split()

  if len(parts) ==  1 :
        term = stemmer.stem(parts[0])
        return  set(index[term])

  if parts[0] == "NOT":
        term = stemmer.stem(parts[1])
        return  allDocs - set(index[term])

  if len(parts) == 3 :
        term1 = stemmer.stem(parts[0])
        operator = parts[1]
        term2 =  stemmer.stem(parts[2])

        docs1 = set(index[term1])
        docs2 = set(index[term2])

        if operator  == "AND":
            return docs1 & docs2
        elif operator == "OR":
            return  docs1 | docs2

  return set ()

