def calculateAp( retrievedIndices , trueLabels, targetLabelId):
  relevantCount = 0
  sumPrecision = 0.0

  for i, idx in enumerate(retrievedIndices ) :
        if trueLabels[idx] == targetLabelId:
            relevantCount += 1
            precisionAtK =  relevantCount / (i + 1 )
            sumPrecision  += precisionAtK

  if relevantCount == 0:
        return 0.0

  return  sumPrecision / relevantCount

"""Ολοκλήρωσα τη διαδικασία αξιολόγησης δημιουργώντας τη συναρτηση evaluateFull, η οποία δέχεται ως όρισμα το όνομα του αλγορίθμου και υπολογίζει τις συνολικές μετρικές απόδοσης. Αρχικά, μηδένισα τους αθροιστές για την ακρίβεια , την ανάκληση και το MAP  και ξεκινησα την επανάληψη για κάθε ερώτημα ελέγχου. Υπολόγισα το average precision για το MAP χρησιμοποιώντας και τα 50 αποτελέσματα, ενώ για την ακρίβεια και την ανάκληση περιορισα τη λίστα στα πρώτα 20 έγγραφα. Σύγκρινα τα έγγραφα με την πραγματική κατηγορία τους (Ground Truth) και αθροισα τα σκορ για να υπολογίσω τους τελικούς μέσους όρους. Τέλος, υπολόγισα το F1 score, που αποτελεί τον αρμονικό μέσο όρο ακρίβειας και ανάκλησης, και εκτυπωσα τα συγκριτικά αποτελέσματα στην οθόνη για να παρατηρήσω ποιος αλγόριθμος απέδωσε καλύτερα."""

def evaluateFull(algorithmName):
    totalPrecision = 0
    totalRecall = 0
    totalMap =  0

    print(f"Αξιολογηση επιδοσης αλγοριθμου {algorithmName} " )

    for queryText, targetCategoryName in evalQueries.items():
        if targetCategoryName not in targetNames: continue
        targetLabelId = targetNames.index( targetCategoryName )

        # Ανακτηση
        if algorithmName ==  "VSM" :
            qVec = vectorizer20News.transform( [" ".join(preprocessText(queryText))])
            sims =  cosine_similarity(qVec, tfidfMatrix20News).flatten()
            topIndices = sims.argsort()[::-1][:50]

        elif algorithmName == "BM25":
            qTokens = preprocessText(queryText )
            scores =  bm2520News.get_scores(qTokens)
            topIndices = np.argsort(scores)[::-1][:50]

        # ΜΑΡ
        ap = calculateAp( topIndices, trueLabels, targetLabelId )
        totalMap += ap

        # Precision και Recall
        top20 = topIndices[:20]
        relevantRetrieved = 0
        for idx in top20:
            if trueLabels[idx]  == targetLabelId:
                relevantRetrieved += 1

        precision = relevantRetrieved / 20
        totalRelevantInDb = trueLabels.count(targetLabelId)

        recall = relevantRetrieved / totalRelevantInDb if totalRelevantInDb > 0 else 0

        totalPrecision += precision
        totalRecall += recall

    avgP = totalPrecision / len(evalQueries)
    avgR =  totalRecall / len(evalQueries)
    mapScore = totalMap / len(evalQueries)

    f1 = 0
    if (avgP + avgR) > 0  :
        f1 = 2 * (avgP * avgR) / (avgP + avgR)

    return avgP , avgR, f1 , mapScore

